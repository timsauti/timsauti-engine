('run-a-chama-that-lasts', 'How to run a chama that lasts and does not end in quarrels', 'Most chamas fail for the same few reasons. Fix them on day one with these simple habits.', $b$
A chama is one of the most powerful ways Kenyans save and invest together. The groups that last share a few habits.

## Write your rules down
Agree in writing on the contribution amount, the due date, the penalty for late payment, how money is shared out or invested, and what happens when a member leaves. Read the rules out at the first meeting and have every member sign.

## Keep the money in a group account
Open a group bank account or a group mobile wallet that needs at least two officials to approve every withdrawal. Avoid keeping chama money in one person's personal M-PESA account, however trusted they are.

## Record every shilling
Keep a simple record of who paid what and when. A shared spreadsheet or a notebook photographed after each meeting both work. Share the totals with every member every month.

## Rotate leadership
Elect the chair, secretary and treasurer for a fixed term. Fresh officials keep the group honest and stop power from settling in one person.

## Grow beyond merry go round
Once contributions are steady, many groups add a savings pool for investment, such as a money market fund, land, or a small shared business. Agree on any investment in writing, and only put in money the group can afford to lock away.

## Register when you grow
A registered self help group can open accounts more easily and apply for some grants and programmes. Ask at your local social development office about registering.
