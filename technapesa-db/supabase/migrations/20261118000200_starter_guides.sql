('protect-yourself-from-sim-swap', 'SIM swap fraud: the warning signs and how to protect your money', 'If your phone suddenly loses network for no reason, act within minutes. Here is why, and what to do.', $b$
In a SIM swap, a fraudster gets your phone number moved to a new SIM card. Once they control your number, they can receive your M-PESA and bank messages and try to reset your accounts.

## The warning signs
Your phone shows "no service" or "SIM not registered" while people around you on the same network have signal. You stop receiving calls and messages. You get a message about a SIM change you did not ask for.

## What to do immediately
Borrow another phone and call your network provider's customer care right away. Ask them to block the line and confirm any recent SIM change. Then call your bank and ask them to freeze mobile banking until you are back in control.

## How to make yourself a harder target
Keep your ID card and copies of it safe. Do not post photos of your ID, your KRA PIN certificate or your date of birth online. Fraudsters use these details to impersonate you at a shop.

Set a strong M-PESA PIN. Avoid your year of birth, 1234, 0000 or repeated numbers.

Use a screen lock on your phone, and do not leave it unlocked with strangers.

Be careful with people who call claiming to be from your network and ask you to "confirm" your details or a code that was just sent to you. That code is often exactly what they need.
