('spot-mpesa-scams', 'How to spot an M-PESA scam before it costs you', 'The five tricks fraudsters use most in Kenya, and the simple checks that beat every one of them.', $b$
Most M-PESA losses do not come from hacking. They come from a person being talked into doing something. Learn the tricks and you are already safer than most.

## 1. The "wrong transfer" message
You get an SMS that looks like an M-PESA confirmation saying someone sent you money, then a call or text begging you to send it back. Before you do anything, open your real M-PESA menu and check your balance or mini statement. A message in your inbox is not money in your account. If the money truly came, the sender can ask Safaricom to reverse it. You never need to send anything yourself.

## 2. Someone asks for your PIN
Safaricom staff, agents, banks and the police will never ask for your M-PESA PIN, not on the phone, not by SMS, not in person. Anyone who asks is a fraudster, every time.

## 3. Fake prizes and promotions
"You have won" messages that ask you to pay a small fee to receive a big prize are scams. A real prize never asks you to pay first. Check promotions only on official pages and numbers.

## 4. Pressure and urgency
Scammers rush you: "your line will be blocked in 10 minutes", "your relative is in hospital, send now". Slow down. Hang up and call the person or company back on a number you already know.

## 5. Strange links
Do not open links in SMS or WhatsApp messages that promise loans, refunds or jobs and then ask for your details. Type the official website yourself.

## What to do if you are targeted
Forward the scam SMS to 333 so Safaricom can act on the number. If you have lost money, call Safaricom customer care immediately and report it at the nearest police station. Then warn your family WhatsApp group, because the same people usually try many numbers.
