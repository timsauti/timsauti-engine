('borrow-from-loan-apps-safely', 'Loan apps and Fuliza: how to borrow without falling into a trap', 'Quick mobile credit can save a bad day or ruin a good year. Five rules before you tap borrow.', $b$
Mobile loans are fast and easy, which is exactly why they need care. These rules keep borrowing working for you.

## 1. Use only licensed lenders
The Central Bank of Kenya licenses digital credit providers and publishes the list on its website. If an app is not on that list, do not borrow from it, no matter how friendly the ads look.

## 2. Look at the total you will repay
Do not look only at the amount you receive. Check the full amount you will pay back, including every fee, and the exact due date. If the app does not show this clearly before you accept, walk away.

## 3. Never give an app your contacts
Some illegal apps read your phone contacts and then shame you to your friends and family if you are late. A licensed lender has no reason to message your contacts. Refuse that permission.

## 4. Fuliza is an overdraft, not free money
Fuliza lets you complete a payment when your M-PESA balance is too low, and it is repaid automatically from the next money you receive. It carries an access fee and a daily charge while the balance is outstanding, so small amounts left unpaid for many days add up. Clear it as soon as you can.

## 5. Borrow for income, not for spending
A loan that helps you restock goods you will sell next week can pay for itself. A loan for spending this weekend has to be paid from money you do not have yet. Missed payments can be reported to credit reference bureaus, which makes future loans harder to get.

## A simple test
Before you borrow, write down where the repayment money will come from and on which date. If you cannot answer, do not borrow yet.
